import os

from dotenv import load_dotenv
from google import genai
from google.genai import types
import json

def get_weather(question):
    question = question.lower()

    if "tomorrow" in question:
        return "Tomorrow will be 28°C with light rain."

    elif "today" in question:
        return "Today is 26°C with showers."

    else:
        return "Please specify today or tomorrow."


        # -----------------------------
# Product Search Function
# -----------------------------

def search_product(product_name):
    return f"Found product: {product_name}"

weather_function = types.FunctionDeclaration(
    name="get_weather",
    description="Get the weather for today or tomorrow.",
    parameters={
        "type": "OBJECT",
        "properties": {
            "question": {
                "type": "STRING",
                "description": "The user's weather question."
            }
        },
        "required": ["question"]
    }
)

# -----------------------------
# Product Function Declaration
# -----------------------------

product_function = types.FunctionDeclaration(
    name="search_product",
    description="Search for a product by name.",
    parameters={
        "type": "OBJECT",
        "properties": {
            "product_name": {
                "type": "STRING",
                "description": "Search for products like laptops, phones, accessories, or other items by product name."
                
            }
        },
        "required": ["product_name"]
    }
)

weather_tool = types.Tool(
    function_declarations=[weather_function]
)

tools = {
    "get_weather": get_weather,
    "search_product": search_product
}
# Load variables from .env
load_dotenv()

# Read API key
api_key = os.getenv("GEMINI_API_KEY")

# Create Gemini client
client = genai.Client(api_key=api_key)

# -----------------------------
# Get User Question
# -----------------------------

# Ask the user a question
question = input("Ask me something: ")

# Send the user's question and available tools to Gemini
# -----------------------------
# Configure Function Calling
# -----------------------------

# Tell Gemini which tools are available
weather_tool = types.Tool(
    function_declarations=[
        weather_function,
        product_function
    ]
)

# Configure Gemini with available tools
config = types.GenerateContentConfig(
    tools=[weather_tool]
)

# -----------------------------
# Send Question to Gemini
# -----------------------------


response = client.models.generate_content(
    model="gemini-3.6-flash",
    contents=question,
    config=config
)

# -----------------------------
# Ask Gemini to Create a Plan
# -----------------------------

planning_prompt = f"""
Create a plan for this user request:

{question}

Return the plan as a list of tool calls.
"""

plan_response = client.models.generate_content(
    model="gemini-3.6-flash",
    contents=planning_prompt,
    
)

print("PLANNING RESPONSE:")
print(plan_response.text)


# -----------------------------
# Convert Plan JSON to Python
# -----------------------------

plan_text = plan_response.text

# Remove Markdown code fences
plan_text = plan_text.replace("```json", "").replace("```", "").strip()

# Convert JSON text to Python
plan = json.loads(plan_text)

print("PLAN:")
print(plan)


# -----------------------------
# Validate Planned Tools
# -----------------------------

print("PLANNED TOOLS:")

for step in plan:
    tool_name = step["tool"]

    if tool_name in tools:
        print("Tool available:", tool_name)
    else:
        print("Tool NOT available:", tool_name)


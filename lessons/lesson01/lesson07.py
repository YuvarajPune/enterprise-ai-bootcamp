print(response)

# Display the type of response object
print(type(response))

# Display all available attributes and methods
print(dir(response))

# Display all parts returned by Gemini
print(response.parts)

# Read the function call from the first response part
function_call = response.parts[0].function_call

# Display the function name
print(function_call.name)

# Display the arguments generated by Gemini
print(function_call.args)

# Find the Python function from the Tool Registry
function = tools[function_call.name]

# Execute the function using Gemini's arguments
answer = function(**function_call.args)

# Display the answer
print(answer)


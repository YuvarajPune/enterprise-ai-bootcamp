# -----------------------------
# Sample Plan
# -----------------------------

plan = [
    {
        "tool": "search_product",
        "args": {
            "product_name": "MacBook Air"
        }
    },
    {
        "tool": "get_weather",
        "args": {
            "question": "weather tomorrow"
        }
    }
]

# -----------------------------
# Execute the Plan
# -----------------------------

for step in plan:

    # Find the Python function from the Tool Registry
    function = tools[step["tool"]]

    # Show which tool is being executed
    print("Executing:", step["tool"])

    # Execute the function using the arguments
    answer = function(**step["args"])

    # Display the result
    print(answer)

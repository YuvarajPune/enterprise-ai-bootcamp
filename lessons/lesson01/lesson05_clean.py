import os

from dotenv import load_dotenv
from google import genai
from google.genai import types

def get_weather(question):
    question = question.lower()

    if "tomorrow" in question:
        return "Tomorrow will be 28°C with light rain."

    elif "today" in question:
        return "Today is 26°C with showers."

    else:
        return "Please specify today or tomorrow."

weather_function = types.FunctionDeclaration(
    name="get_weather",
    description="Get the weather for today or tomorrow.",
    parameters={
        "type": "OBJECT",
        "properties": {
            "question": {
                "type": "STRING",
                "description": "The user's weather question."
            }
        },
        "required": ["question"]
    }
)

weather_tool = types.Tool(
    function_declarations=[weather_function]
)

tools = {
    "get_weather": get_weather
}

# Load variables from .env
load_dotenv()

# Read API key
api_key = os.getenv("GEMINI_API_KEY")

# Create Gemini client
client = genai.Client(api_key=api_key)

# -----------------------------
# Get User Question
# -----------------------------

# Ask the user a question
question = input("Ask me something: ")

# -----------------------------
# Send Question to Gemini
# -----------------------------

# Send the user's question and available tools to Gemini
# -----------------------------
# Configure Function Calling
# -----------------------------

# Tell Gemini which tools are available
config = types.GenerateContentConfig(
    tools=[weather_tool]
)

# -----------------------------
# Send Question to Gemini
# -----------------------------

response = client.models.generate_content(
    model="gemini-3.6-flash",
    contents=question,
    config=config
)

# Display the complete response from Gemini
print(response)

# Display the type of response object
print(type(response))

# Display all available attributes and methods
print(dir(response))

# Display all parts returned by Gemini
print(response.parts)

# Read the function call from the first response part
function_call = response.parts[0].function_call

# Display the function name
print(function_call.name)

# Display the arguments generated by Gemini
print(function_call.args)

# Find the Python function from the Tool Registry
function = tools[function_call.name]

# Execute the function using Gemini's arguments
answer = function(**function_call.args)

# Display the answer
print(answer)